begin;

create table public.panel_operators (
  id bigint generated by default as identity not null,
  user_id uuid not null references auth.users (id) on delete cascade,
  constraint panel_operators_pkey primary key (id),
  constraint panel_operators_user_id_key unique (user_id)
);

alter table public.panel_operators enable row level security;
revoke all on table public.panel_operators from public, anon, authenticated;
grant select on table public.panel_operators to authenticated;
grant select on table public.panel_operators to service_role;

create policy "operators can read own membership"
  on public.panel_operators
  for select
  to authenticated
  using (user_id = (select auth.uid()));

revoke all on table public.clients from public, anon, authenticated;
revoke all on table public.messages from public, anon, authenticated;
grant select on table public.messages to authenticated;

drop policy if exists "anon can read messages for realtime" on public.messages;

create policy "operators can read messages for realtime"
  on public.messages
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.panel_operators
      where user_id = (select auth.uid())
    )
  );

commit;
